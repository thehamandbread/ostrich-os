//! What the palette writes: CSS blocks (inside markers, so the rest of each file is kept),
//! a Ghostty theme, palette.json, and the nearest of GNOME's standard accents.

use crate::color::{contrast, hue_distance, Rgb};

pub const BEGIN: &str = "/* ubuntu-ostrich theme: begin (managed; edit with `ostrich theme`) */";
pub const END: &str = "/* ubuntu-ostrich theme: end */";

/// GNOME's standard accent colours (libadwaita 1.6+), as `accent-color` values.
pub const GNOME_ACCENTS: [(&str, &str); 9] = [
    ("blue", "#3584e4"),
    ("teal", "#2190a4"),
    ("green", "#3a944a"),
    ("yellow", "#c88800"),
    ("orange", "#ed5b00"),
    ("red", "#e62d42"),
    ("pink", "#d56199"),
    ("purple", "#9141ac"),
    ("slate", "#6f8396"),
];

/// The GNOME accent name closest in hue (slate for near-greys).
pub fn nearest_gnome_accent(c: Rgb) -> &'static str {
    let lab = c.to_lab();
    if lab.chroma() < 0.05 {
        return "slate";
    }
    GNOME_ACCENTS
        .iter()
        .filter(|(n, _)| *n != "slate")
        .min_by(|a, b| {
            let ha = Rgb::from_hex(a.1).unwrap().to_lab().hue();
            let hb = Rgb::from_hex(b.1).unwrap().to_lab().hue();
            hue_distance(ha, lab.hue()).total_cmp(&hue_distance(hb, lab.hue()))
        })
        .map(|(n, _)| *n)
        .unwrap()
}

/// An accent as a fill that carries text, and that text: 4.5:1 or better (WCAG AA for small
/// text). White on the accent if it passes; black on a clearly light accent (yellow); otherwise
/// white on the accent darkened just enough (`accentStrong`: GNOME's blue #3584e4 is 3.8:1 with
/// white). The plain accent stays for fills without text (toggles, focus rings, the dock's dot).
pub fn accent_pair(c: Rgb) -> (Rgb, Rgb) {
    let white = Rgb {
        r: 1.0,
        g: 1.0,
        b: 1.0,
    };
    let black = Rgb {
        r: 0.0,
        g: 0.0,
        b: 0.0,
    };
    if contrast(c, white) >= 4.5 {
        return (c, white);
    }
    if contrast(c, black) >= 7.0 {
        return (c, black);
    }
    let mut lab = c.to_lab();
    let mut bg = c;
    while contrast(bg, white) < 4.5 && lab.l > 0.0 {
        lab.l -= 0.01;
        bg = lab.to_rgb();
    }
    (bg, white)
}

/// libadwaita (GTK 4) accent override.
pub fn gtk4_css(accent: Rgb) -> String {
    format!(
        "{BEGIN}\n:root {{\n  --accent-bg-color: {bg};\n  --accent-fg-color: {fg};\n}}\n{END}\n",
        bg = accent_pair(accent).0.hex(),
        fg = accent_pair(accent).1.hex()
    )
}

/// GTK 3 (Adwaita/Yaru) named colours.
pub fn gtk3_css(accent: Rgb) -> String {
    format!(
        "{BEGIN}\n@define-color accent_bg_color {bg};\n@define-color accent_fg_color {fg};\n@define-color accent_color {bg};\n@define-color theme_selected_bg_color {bg};\n@define-color theme_selected_fg_color {fg};\n{END}\n",
        bg = accent_pair(accent).0.hex(),
        fg = accent_pair(accent).1.hex()
    )
}

/// Replaces (or appends) the managed block in an existing file's text; everything else is kept.
pub fn merge_block(existing: &str, block: &str) -> String {
    if let (Some(start), Some(end)) = (existing.find(BEGIN), existing.find(END)) {
        if end > start {
            let after = &existing[end + END.len()..];
            let after = after.strip_prefix('\n').unwrap_or(after);
            return format!("{}{}{}", &existing[..start], block, after);
        }
    }
    if existing.is_empty() {
        block.to_string()
    } else if existing.ends_with('\n') {
        format!("{existing}\n{block}")
    } else {
        format!("{existing}\n\n{block}")
    }
}

/// Our block in `text` (with its line end), if there is one.
pub fn our_block(text: &str) -> Option<&str> {
    let start = text.find(BEGIN)?;
    let end = start + text[start..].find(END)? + END.len();
    Some(&text[start..end + usize::from(text[end..].starts_with('\n'))])
}

/// `existing` with our block taken out (and the blank line `merge_block` put before it).
pub fn strip_block(existing: &str) -> String {
    let Some(block) = our_block(existing) else {
        return existing.to_string();
    };
    let start = existing.find(block).unwrap_or(0);
    let before = &existing[..start];
    let before = before
        .strip_suffix('\n')
        .filter(|b| b.ends_with('\n'))
        .unwrap_or(before);
    format!("{before}{}", &existing[start + block.len()..])
}

/// A Ghostty theme using the accent for cursor and selection (palette colours stay the user's).
pub fn ghostty_theme(accent: Rgb) -> String {
    format!(
        "# Generated by `ostrich theme` (Ubuntu Ostrich). Use with: theme = ubuntu-ostrich\ncursor-color = {a}\nselection-background = {a}\nselection-foreground = {fg}\n",
        a = accent_pair(accent).0.hex(),
        fg = accent_pair(accent).1.hex()
    )
}

fn json_str(s: &str) -> String {
    let mut out = String::from('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// palette.json for the shell extensions: {"accent", "accentStrong", "accentFg", "gnomeAccent",
/// "wallpaper", "candidates"}. accentFg is the text on accentStrong.
pub fn palette_json(accent: Rgb, candidates: &[Rgb], wallpaper: &str) -> String {
    let list: Vec<String> = candidates.iter().map(|c| json_str(&c.hex())).collect();
    format!(
        "{{\n  \"accent\": {},\n  \"accentStrong\": {},\n  \"accentFg\": {},\n  \"gnomeAccent\": {},\n  \"wallpaper\": {},\n  \"candidates\": [{}]\n}}\n",
        json_str(&accent.hex()),
        json_str(&accent_pair(accent).0.hex()),
        json_str(&accent_pair(accent).1.hex()),
        json_str(nearest_gnome_accent(accent)),
        json_str(wallpaper),
        list.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rgb(h: &str) -> Rgb {
        Rgb::from_hex(h).unwrap()
    }

    #[test]
    fn nearest_accent_matches_gnome_colours() {
        for (name, hex) in GNOME_ACCENTS {
            assert_eq!(nearest_gnome_accent(rgb(hex)), name, "{hex}");
        }
        assert_eq!(nearest_gnome_accent(rgb("#777777")), "slate");
    }

    #[test]
    fn merge_replaces_only_the_managed_block() {
        let user = "window { color: red; }\n";
        let once = merge_block(user, &gtk4_css(rgb("#1c62b9")));
        assert!(once.starts_with(user));
        let twice = merge_block(&once, &gtk4_css(rgb("#b84700")));
        assert!(twice.starts_with(user));
        assert!(twice.contains("#b84700") && !twice.contains("#1c62b9"));
        assert_eq!(twice.matches(BEGIN).count(), 1);
        // and user text after the block survives too
        let with_tail = format!("{twice}.x {{}}\n");
        let again = merge_block(&with_tail, &gtk4_css(rgb("#3a944a")));
        assert!(again.ends_with(".x {}\n"));
    }

    #[test]
    fn merge_into_empty_file() {
        assert_eq!(merge_block("", "B\n"), "B\n");
    }

    #[test]
    fn json_is_escaped() {
        let j = palette_json(rgb("#3584e4"), &[rgb("#3584e4")], "/home/u/my \"wall\".jpg");
        assert!(j.contains(r#""wallpaper": "/home/u/my \"wall\".jpg""#));
        assert!(j.contains(r#""gnomeAccent": "blue""#));
    }

    #[test]
    fn text_on_the_accent_is_readable() {
        for hex in [
            "#3584e4", "#ed5b00", "#6f8396", "#f8e45c", "#2ec27e", "#1c1c1c",
        ] {
            let (bg, fg) = accent_pair(rgb(hex));
            assert!(contrast(bg, fg) >= 4.5, "{hex}: {}", contrast(bg, fg));
        }
        // Blue keeps white text on a darker blue; yellow gets black text and stays yellow.
        let (bg, fg) = accent_pair(rgb("#3584e4"));
        assert_eq!(fg.hex(), "#ffffff");
        assert!(bg.hex() != "#3584e4" && contrast(bg, fg) < 5.0);
        assert_eq!(
            accent_pair(rgb("#f8e45c")),
            (rgb("#f8e45c"), rgb("#000000"))
        );
    }
}
